"""
fixture_author.py: Minimal crash reproducer authoring engine.
Generates an isolated reproducer script in .tmp/reproduce_error.py
so patches can be verified before modifying production code.
"""
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent
ROOT_DIR = HARNESS_DIR.parent
TMP_DIR = ROOT_DIR / ".tmp"

def author_reproducer(crash_record: dict) -> Path:
    """
    Generates .tmp/reproduce_error.py based on captured crash metadata.
    """
    TMP_DIR.mkdir(parents=True, exist_ok=True)
    reproducer_path = TMP_DIR / "reproduce_error.py"
    
    script_target = crash_record.get("script", "")
    args = crash_record.get("args", [])
    
    code = f"""# Minimal reproducer generated by Self Annealing Engine.
# Original script: {script_target}
# Target failure: {crash_record.get('exception_name', 'Error')}

import subprocess
import sys

SCRIPT_TARGET = {repr(script_target)}
ARGS = {repr(args)}

def test_reproduction():
    cmd = [sys.executable, SCRIPT_TARGET] + ARGS
    print(f"Executing reproducer: {' '.join(cmd)}")
    res = subprocess.run(cmd, capture_output=True, text=True)
    print("Process exited with code:", res.returncode)
    if res.returncode != 0:
        print("Observed error trace tail:")
        print(res.stderr[-500:] if res.stderr else "No stderr")
        return True
    print("Script succeeded without error. Reproduction failed or bug is fixed.")
    return False

if __name__ == "__main__":
    reproduced = test_reproduction()
    sys.exit(0 if reproduced else 1)
"""
    with open(reproducer_path, "w", encoding="utf-8") as f:
        f.write(code)
    
    return reproducer_path
